import json, subprocess, sys
P = "/tmp/claude-0/reel2/public"
D = {
 "c04": dict(sil=[(163.912, 169.472)], white=[(163.56, 169.47)]),
 "c07": dict(extra=[(34.69, 37.95)], sil=[(226.193, 233.379), (283.681, 290.736)], white=[(226.03, 233.50), (283.55, 290.86)]),
 "c09": dict(extra=[(65.05, 69.80), (81.02, 83.41)], sil=[], white=[]),
 "c10": dict(sil=[(150.197, 154.284), (213.157, 217.25)], white=[(0.17, 0.33), (149.85, 154.59), (212.81, 217.55)]),
 "c11": dict(sil=[(12.931, 16.791), (150.109, 153.817), (204.701, 208.772)], white=[(12.58, 17.08), (149.75, 153.75), (204.67, 208.71), (271.27, 271.62)]),
 "c17": dict(sil=[(67.021, 71.173)], white=[]),
 "c12": dict(sil=[(73.251, 77.041), (99.177, 103.399), (132.444, 136.531)], white=[(0.17, 0.33), (72.91, 77.34), (98.83, 103.70), (132.10, 136.84), (192.09, 192.43)]),
}
def dur(f): return float(subprocess.check_output(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",f]))
def cs(t, cuts):
    d = 0
    for a, b in cuts:
        if t >= b: d += b - a
        elif t > a: d += t - a
    return t - d
TS = "/tmp/claude-0/reel2/src/clips/cuts.ts"
src = open(TS).read()
out = json.loads(src[src.index("> = ") + 4:].rstrip().rstrip(";"))
only = sys.argv[1:] or list(D)
for k, d in D.items():
    if k not in only: continue
    vd = dur(f"{P}/{k}/voice.m4a")
    cuts = [(round(a + 0.15, 3), round(min(b - 0.15, vd) if b < vd - 0.01 else vd, 3)) for a, b in d["sil"]]
    cuts = sorted(cuts + [tuple(x) for x in d.get("extra", [])])
    keep, t = [], 0.0
    for a, b in cuts:
        keep.append((t, a)); t = b
    if t < vd - 0.01: keep.append((t, vd))
    vf = "".join(f"[0:v]trim={a}:{b},setpts=PTS-STARTPTS[v{i}];" for i, (a, b) in enumerate(keep)) + "".join(f"[v{i}]" for i in range(len(keep))) + f"concat=n={len(keep)}:v=1:a=0[v]"
    af = "".join(f"[0:a]atrim={a}:{b},asetpts=PTS-STARTPTS[a{i}];" for i, (a, b) in enumerate(keep)) + "".join(f"[a{i}]" for i in range(len(keep))) + f"concat=n={len(keep)}:v=0:a=1[a]"
    subprocess.run(["ffmpeg","-y","-loglevel","error","-i",f"{P}/{k}/cam.mp4","-filter_complex",vf,"-map","[v]","-c:v","libx264","-crf","18","-preset","fast","-pix_fmt","yuv420p",f"{P}/{k}/cam.cut.mp4"], check=True)
    subprocess.run(["ffmpeg","-y","-loglevel","error","-i",f"{P}/{k}/voice.m4a","-filter_complex",af,"-map","[a]","-c:a","aac","-b:a","160k",f"{P}/{k}/voice.cut.m4a"], check=True)
    covers = []
    for i, (a, b) in enumerate(d["white"]):
        src_t = 0.6 if a < 1 else max(0, a - 0.2)
        img = f"{k}/still{i}.png"
        subprocess.run(["ffmpeg","-y","-loglevel","error","-ss",str(src_t),"-i",f"{P}/{k}/cam.mp4","-frames:v","1",f"{P}/{img}"], check=True)
        covers.append([round(cs(a, cuts) - 0.1, 3), round(cs(b, cuts) + 0.1, 3), img])
    out[k] = dict(cuts=cuts, covers=covers)
    print(k, "cut", round(vd, 2), "->", round(dur(f"{P}/{k}/voice.cut.m4a"), 2), round(dur(f"{P}/{k}/cam.cut.mp4"), 2), covers)
ts = "/* Silent gaps cut from the voice and camera (white slide transitions in the source course), and camera stills that\n * cover the few white frames left at each cut. Generated by the clip tooling; times are in voice seconds. */\n"
ts += "export type Cuts = [number, number][];\nexport type Cover = [number, number, string];\n"
ts += "export const CUTS: Record<string, { cuts: Cuts; covers: Cover[] }> = " + json.dumps(out, indent=1) + ";\n"
open("/tmp/claude-0/reel2/src/clips/cuts.ts", "w").write(ts)
