-- 0046: admin panel Phase 1, customer support (docs/admin/README.md, SUP-1 to SUP-12).
-- Tickets and their messages, macros, the SLA and assignment settings, and business-hours due times. Email to
-- support@uxgate.org arrives through the Worker's email handler (apps/web/cf-worker.ts) and /api/support/inbound;
-- refund requests and lesson reports ("this question is broken or unclear") become tickets here, by trigger.
-- Service role only, like every admin table.

create table public.support_settings (
  id smallint primary key default 1 check (id = 1),
  first_reply_hours integer not null default 24 check (first_reply_hours between 1 and 240),
  resolve_hours integer not null default 72 check (resolve_hours between 1 and 720),
  -- Business hours by the learner's language, in Cairo time. 0 = Sunday ... 6 = Saturday.
  hours jsonb not null default '{"tz": "Africa/Cairo", "ar": {"days": [6, 0, 1, 2, 3, 4], "start": 9, "end": 17}, "en": {"days": [1, 2, 3, 4, 5], "start": 9, "end": 17}}',
  warn_before_minutes integer not null default 120,
  assignment text not null default 'manual' check (assignment in ('manual', 'round_robin', 'category')),
  category_assignees jsonb not null default '{}',   -- {"billing": "<admin user id>", ...}
  round_robin_last uuid,
  survey boolean not null default true,
  survey_text jsonb not null default '{"en": "How did we do?", "ar": "كيف كانت تجربتك معنا؟"}',
  -- A support agent refunds up to this amount (USD cents, other currencies at the panel's rate); more needs approval.
  refund_limit_usd_minor integer not null default 5000 check (refund_limit_usd_minor >= 0),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id) on delete set null
);
insert into public.support_settings (id) values (1) on conflict do nothing;

create table public.support_tickets (
  id bigint generated by default as identity (start with 1001) primary key,
  user_id uuid references auth.users (id) on delete set null,
  email text not null,
  name text,
  subject text not null check (char_length(subject) between 1 and 300),
  channel text not null check (channel in ('email', 'form', 'lesson_report', 'refund', 'appeal', 'system')),
  category text not null default 'other' check (category in ('account', 'billing', 'content', 'technical', 'certificate', 'idea', 'other')),
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  status text not null default 'new' check (status in ('new', 'open', 'waiting_learner', 'waiting_team', 'resolved', 'closed')),
  assignee_id uuid references auth.users (id) on delete set null,
  tags text[] not null default '{}',
  language text not null default 'en' check (language in ('en', 'ar')),
  link_type text check (link_type in ('payment', 'refund_request', 'review_request', 'certificate', 'lesson')),
  link_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  first_reply_due timestamptz,
  resolve_due timestamptz,
  first_replied_at timestamptz,
  resolved_at timestamptz,
  satisfaction text check (satisfaction in ('good', 'bad')),
  satisfaction_comment text check (satisfaction_comment is null or char_length(satisfaction_comment) <= 1000),
  satisfaction_token_hash text unique,
  satisfaction_at timestamptz
);
create index support_tickets_status on public.support_tickets (status, last_message_at desc);
create index support_tickets_assignee on public.support_tickets (assignee_id, status);
create index support_tickets_user on public.support_tickets (user_id, created_at desc);
create index support_tickets_email on public.support_tickets (lower(email), created_at desc);
create index support_tickets_due on public.support_tickets (first_reply_due) where first_replied_at is null;

create table public.support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id bigint not null references public.support_tickets (id) on delete cascade,
  kind text not null check (kind in ('inbound', 'reply', 'note', 'event')),
  author_id uuid references auth.users (id) on delete set null,
  from_email text,
  body text not null check (char_length(body) between 1 and 20000),
  language text check (language in ('en', 'ar')),
  mentions uuid[] not null default '{}',
  email_message_id text,          -- inbound Message-ID, or the id the email provider gave our reply
  delivery text check (delivery in ('sent', 'failed', 'skipped')),
  attachments integer not null default 0,
  created_at timestamptz not null default now()
);
create index support_messages_ticket on public.support_messages (ticket_id, created_at);
create unique index support_messages_inbound_once on public.support_messages (email_message_id) where kind = 'inbound' and email_message_id is not null;

create table public.support_macros (
  id uuid primary key default gen_random_uuid(),
