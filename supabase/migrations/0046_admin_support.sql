  uses integer not null default 0,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ───────── business-hours due times (SUP-7) ─────────

-- p_hours of business time after p_from, in the business hours of the ticket's language.
create function public.support_due(p_from timestamptz, p_hours integer, p_lang text)
returns timestamptz language plpgsql stable set search_path = public as $$
declare
  cfg jsonb := (select hours from public.support_settings where id = 1);
  tz text := coalesce(cfg ->> 'tz', 'Africa/Cairo');
  h jsonb := coalesce(cfg -> coalesce(nullif(p_lang, ''), 'en'), cfg -> 'en');
  v_days int[] := array(select jsonb_array_elements_text(coalesce(h -> 'days', '[1,2,3,4,5]'))::int);
  v_start int := coalesce((h ->> 'start')::int, 9);
  v_end int := coalesce((h ->> 'end')::int, 17);
  v_left interval := make_interval(hours => p_hours);
  t timestamp := p_from at time zone tz;
  d0 timestamp; s timestamp; e timestamp;
  i int := 0;
begin
  if v_end <= v_start or cardinality(v_days) = 0 then return p_from + v_left; end if;
  while i < 400 loop
    d0 := date_trunc('day', t);
    if extract(dow from d0)::int = any (v_days) then
      s := greatest(t, d0 + make_interval(hours => v_start));
      e := d0 + make_interval(hours => v_end);
      if s < e then
        if e - s >= v_left then return (s + v_left) at time zone tz; end if;
        v_left := v_left - (e - s);
      end if;
    end if;
    t := d0 + interval '1 day';
    i := i + 1;
  end loop;
  return p_from + make_interval(hours => p_hours);
end $$;

-- New tickets get their due times and, by the assignment rule, an owner.
create function public.support_ticket_defaults() returns trigger language plpgsql security definer set search_path = public as $$
declare
  cfg public.support_settings;
  v_next uuid;
begin
  select * into cfg from public.support_settings where id = 1;
  new.first_reply_due := coalesce(new.first_reply_due, public.support_due(new.created_at, coalesce(cfg.first_reply_hours, 24), new.language));
  new.resolve_due := coalesce(new.resolve_due, public.support_due(new.created_at, coalesce(cfg.resolve_hours, 72), new.language));
  if new.user_id is null then
    select u.id into new.user_id from auth.users u where lower(u.email) = lower(new.email) limit 1;
  end if;
  if new.assignee_id is null and cfg.assignment = 'category' then
    new.assignee_id := nullif(cfg.category_assignees ->> new.category, '')::uuid;
  elsif new.assignee_id is null and cfg.assignment = 'round_robin' then
    -- The next active member who can reply to tickets, after the last one given a ticket.
    select m.user_id into v_next from public.admin_members m
      where m.status = 'active' and 'support.reply' = any (public.admin_perms(m.user_id))
        and (cfg.round_robin_last is null or m.user_id > cfg.round_robin_last)
      order by m.user_id limit 1;
    if v_next is null then
      select m.user_id into v_next from public.admin_members m
        where m.status = 'active' and 'support.reply' = any (public.admin_perms(m.user_id)) order by m.user_id limit 1;
    end if;
    new.assignee_id := v_next;
    update public.support_settings set round_robin_last = v_next where id = 1;
  end if;
  return new;
end $$;
create trigger support_ticket_defaults before insert on public.support_tickets for each row execute function public.support_ticket_defaults();

-- ───────── tickets from refund requests and lesson reports (SUP-1, SUP-9) ─────────

create function public.support_from_refund() returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_email text;
  v_locale text;
  v_id bigint;
begin
  select u.email, coalesce(p.locale, 'en') into v_email, v_locale from auth.users u left join public.profiles p on p.user_id = u.id where u.id = new.user_id;
  insert into public.support_tickets (user_id, email, subject, channel, category, status, language, link_type, link_id)
  values (new.user_id, coalesce(v_email, 'unknown@uxgate.org'), case when v_locale = 'ar' then 'طلب استرداد مبلغ' else 'Refund request' end,
          'refund', 'billing', 'waiting_team', v_locale, 'refund_request', new.id::text)
  returning id into v_id;
  insert into public.support_messages (ticket_id, kind, from_email, body, language) values (v_id, 'inbound', v_email, new.reason, v_locale);
  return new;
end $$;
create trigger support_from_refund after insert on public.refund_requests for each row execute function public.support_from_refund();

create function public.support_from_review() returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_email text;
  v_locale text;
  v_id bigint;
begin
  -- Only reports that the question itself is broken or unclear are tickets; "my answer also works" is an appeal,
  -- decided on the Appeals page.
  if new.reason not in ('broken', 'unclear') then return new; end if;
  select u.email, coalesce(p.locale, 'en') into v_email, v_locale from auth.users u left join public.profiles p on p.user_id = u.id where u.id = new.user_id;
  insert into public.support_tickets (user_id, email, subject, channel, category, status, language, link_type, link_id)
  values (new.user_id, coalesce(v_email, 'unknown@uxgate.org'),
          (case when v_locale = 'ar' then 'بلاغ عن سؤال: ' else 'Lesson report: ' end) || new.lesson_id || ' ' || new.step_id,
          'lesson_report', 'content', 'new', v_locale, 'review_request', new.id::text)
  returning id into v_id;
  insert into public.support_messages (ticket_id, kind, from_email, body, language)
  values (v_id, 'inbound', v_email, coalesce(nullif(new.note, ''), case new.reason when 'broken' then 'Something is broken in this question.' else 'This question is unclear.' end), v_locale);
  return new;
end $$;
create trigger support_from_review after insert on public.review_requests for each row execute function public.support_from_review();

