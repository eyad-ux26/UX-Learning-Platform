// Builds app/styles/uxgate.css (the approved component stylesheet) and app/styles/icons.css
// (Phosphor icons as CSS masks) from docs/design/system/uxgate.css. Outputs are committed.
// Run: npm run assets -w @uxgate/web
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const phosphor = path.resolve(here, "../../../node_modules/@phosphor-icons/core");
const src = fs.readFileSync(path.resolve(here, "../../../docs/design/system/uxgate.css"), "utf8");

// Design name -> Phosphor name, where they differ.
const RENAME = {
  arrow: "arrow-right", review: "arrows-clockwise", caret: "caret-down", freeze: "snowflake",
  signout: "sign-out", google: "google-logo", apple: "apple-logo", comment: "chat-text",
  chat: "chat-circle", bolt: "lightning", bulb: "lightbulb", map: "map-trifold", mail: "envelope-simple",
  search: "magnifying-glass",
};

// Icons the app needs that the design canvas does not use (yet).
const EXTRA = ["ph-eye-slash"];
const names = [...src.matchAll(/^\.(ph-[a-z-]+) \{ --i: url\(\/_blob\//gm)].map((m) => m[1]).concat(EXTRA);
const rules = names.map((cls) => {
  let base = cls.slice(3);
  const fill = base.endsWith("-fill");
  if (fill) base = base.slice(0, -5);
  const ph = RENAME[base] ?? base;
  const file = fill
    ? path.join(phosphor, "assets/fill", `${ph}-fill.svg`)
    : path.join(phosphor, "assets/regular", `${ph}.svg`);
  if (!fs.existsSync(file)) throw new Error(`No Phosphor icon for ${cls}: ${file}`);
  const svg = fs.readFileSync(file, "utf8").trim().replace(/\s+/g, " ");
  return `.${cls} { --i: url("data:image/svg+xml;utf8,${encodeURIComponent(svg)}"); }`;
});

const css = src.replace(/^\.ph-[a-z-]+ \{ --i: url\(\/_blob\/[0-9a-f]+\); \}\n/gm, "");
if (/_blob/.test(css)) throw new Error("uxgate.css still references /_blob");
const out = path.resolve(here, "../app/styles");
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "uxgate.css"), css);
fs.writeFileSync(path.join(out, "icons.css"), `/* Generated by scripts/build-assets.mjs. Do not edit. */\n${rules.join("\n")}\n`);
console.log(`assets: ${names.length} icons`);
