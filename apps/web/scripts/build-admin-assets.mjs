// Builds the admin panel's stylesheet and icons (Phase 1 design, docs/design/admin/phase-1-boards/admin.css):
//   app/admin/admin.css        the design's work-tool layer, without its canvas-only icon and logo references
//   app/admin/admin-icons.css  every Phosphor icon the admin code uses (".i i-<name>"), as CSS masks
// Outputs are committed. Run: npm run admin:assets -w @uxgate/web [path to the design admin.css]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "..");
const phosphor = path.resolve(web, "../../node_modules/@phosphor-icons/core/assets");
const svgOf = (name) => {
  const fill = name.endsWith("-fill");
  const file = path.join(phosphor, fill ? "fill" : "regular", `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`No Phosphor icon "${name}" (${file})`);
  return fs.readFileSync(file, "utf8").trim().replace(/\s+/g, " ");
};
const uri = (name) => `url("data:image/svg+xml;utf8,${encodeURIComponent(svgOf(name))}")`;

// The app's CSS rule (scripts/lint-logical.mjs): logical properties instead of left/right. The panel is laid out left to
// right, so these give the same result, and Arabic blocks inside it (dir="rtl") line up the right way.
const logical = (css) => css
  .replace(/border-(top|bottom)-(left|right)-radius\s*:/g, (_, v, h) => `border-${v === "top" ? "start" : "end"}-${h === "left" ? "start" : "end"}-radius:`)
  .replace(/(^|[;{\s])(margin|padding|scroll-margin|scroll-padding)-(left|right)\s*:/g, (_, a, p, h) => `${a}${p}-inline-${h === "left" ? "start" : "end"}:`)
  .replace(/(^|[;{\s])border-(left|right)(-[a-z]+)?\s*:/g, (_, a, h, rest = "") => `${a}border-inline-${h === "left" ? "start" : "end"}${rest}:`)
  .replace(/(^|[;{\s])(left|right)\s*:/g, (_, a, h) => `${a}inset-inline-${h === "left" ? "start" : "end"}:`)
  .replace(/text-align\s*:\s*(left|right)/g, (_, h) => `text-align: ${h === "left" ? "start" : "end"}`)
  .replace(/(^|[;{\s])float\s*:\s*(left|right)/g, (_, a, h) => `${a}float: inline-${h === "left" ? "start" : "end"}`);

const src = process.argv[2];
const adminCss = path.join(web, "app/admin/admin.css");
if (!src && fs.existsSync(adminCss)) fs.writeFileSync(adminCss, logical(fs.readFileSync(adminCss, "utf8")));
if (src) {
  let css = fs.readFileSync(src, "utf8");
  css = css.replace(/^\.i-[a-z0-9-]+\{--i:url\(\/_blob\/[0-9a-f]+\)\}\n/gm, "");
  // The checkbox tick uses the "check" icon.
  css = css.replace(/url\(\/_blob\/0ef956c17c198a820c8c0586d11c8a2d\)/g, uri("check"));
  if (/_blob/.test(css)) throw new Error("admin.css still references /_blob");
  fs.writeFileSync(adminCss, `/* Generated from the Phase 1 design by scripts/build-admin-assets.mjs. */\n${logical(css)}`);
}

// Icons named anywhere in the admin code.
const names = new Set(["check", "x", "caret-down", "magnifying-glass", "warning", "info", "check-circle-fill", "lock-simple", "eye", "eye-slash"]);
const scan = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const f = path.join(dir, e.name);
    if (e.isDirectory()) scan(f);
    else if (/\.(tsx?|css)$/.test(e.name) && !e.name.endsWith("admin-icons.css")) {
      const t = fs.readFileSync(f, "utf8");
      for (const m of t.matchAll(/\bi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) names.add(m[1]);
      for (const m of t.matchAll(/icon:\s*"([a-z0-9-]+)"/g)) names.add(m[1]);
      for (const m of t.matchAll(/item\("[a-z0-9]+", "[^"]+", "([a-z0-9-]+)"/g)) names.add(m[1]);
      // <I n="tray" />, icon="plus", n={x ? "a" : "b"} and the TONE_ICON / ROLE_ICON maps: every quoted name on such a
      // line; names that are not Phosphor icons are dropped below.
      for (const line of t.split("\n")) {
        if (!/\bn=|\bicon\b|_ICON\b/.test(line)) continue;
        for (const m of line.matchAll(/"([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"/g)) names.add(m[1]);
      }
      // Status tables such as RELEASE_STATUS: ["good", "eye", "In review"] (tone, icon, label).
      for (const m of t.matchAll(/\["(?:good|info|wait|bad|off)", "([a-z0-9-]+)"/g)) names.add(m[1]);
    }
  }
};
scan(path.join(web, "app/admin"));
scan(path.join(web, "lib/admin"));
scan(path.join(web, "components/admin"));
const skip = new Set(["d"]); // not icons: class fragments such as "i-d"
const rules = [...names].filter((n) => !skip.has(n)).sort().map((n) => {
  try { return `.i-${n}{--i:${uri(n)}}`; } catch { return null; } // not a Phosphor icon name
}).filter(Boolean);
fs.writeFileSync(path.join(web, "app/admin/admin-icons.css"), `/* Generated by scripts/build-admin-assets.mjs: Phosphor icons used by the admin panel. */\n${rules.join("\n")}\n`);
console.log(`admin icons: ${rules.length}`);
