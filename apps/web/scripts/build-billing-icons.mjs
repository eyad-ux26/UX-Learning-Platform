// Builds app/styles/billing-icons.css: the Phosphor icons slice 5 adds (canvas v63 "Slice 5" block), as CSS masks,
// the same way build-assets.mjs does for the rest. Kept apart from icons.css so the billing icons have one owner.
// Run: node scripts/build-billing-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const phosphor = path.resolve(here, "../../../node_modules/@phosphor-icons/core");
const ICONS = {
  "credit-card": "credit-card", receipt: "receipt", wallet: "wallet", refund: "arrow-u-up-left", tag: "tag", student: "student",
  "lock-open": "lock-simple-open", retry: "arrow-clockwise", swap: "swap", external: "arrow-square-out", hourglass: "hourglass",
  download: "download-simple", "shield-check": "shield-check", "chat-text": "chat-text", certificate: "certificate", lifebuoy: "lifebuoy",
  calendar: "calendar-blank", warning: "warning", info: "info", "caret-end": "caret-right",
};
const rules = Object.entries(ICONS).map(([cls, ph]) => {
  const file = path.join(phosphor, "assets/regular", `${ph}.svg`);
  if (!fs.existsSync(file)) throw new Error(`No Phosphor icon ${ph}`);
  const svg = fs.readFileSync(file, "utf8").trim().replace(/\s+/g, " ");
  return `.ph-${cls} { --i: url("data:image/svg+xml;utf8,${encodeURIComponent(svg)}"); }`;
});
fs.writeFileSync(path.resolve(here, "../app/styles/billing-icons.css"), `/* Generated by scripts/build-billing-icons.mjs. Do not edit. */\n${rules.join("\n")}\n`);
console.log(`billing icons: ${rules.length}`);
